class Solution:
    def countCommas(self, n: int) -> int:
        if n >= 1000 and n < 10**6:
            return (n - 1000) + 1
        elif n >= 10**6 and n < 10**9:
            return (10**6 - 1000) + 1 + (n - 10**6) * 2 + 1
        elif n >= 10**9 and n < 10**12:
            return (10**6 - 1000) + (10**9 - 10**6) * 2 + (n - 10**9) * 3 + 3
        elif n >= 10**12 and n < 10**15:
            return (10**6 - 1000) + (10**9 - 10**6) * 2 + (10**12 - 10**9) * 3 + (n - 10**12) * 4 + 4
        elif n == 10**15:
            return (10**6 - 1000) + (10**9 - 10**6) * 2 + (10**12 - 10**9) * 3 + (10**15 - 10**12) * 4 + 5
        return 0